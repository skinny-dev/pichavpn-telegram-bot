// node export_studio.mjs → ../../serverless-bot/tgcloud/lib/studio_calendar.js (generated): every occasion of 1405 and 1406 with its date,
// so the Studio (Mini App) can show the calendar without the growth/ folder. Edit occasions.mjs, not the output.
import fs from 'node:fs'
import { j2g, g2j, addDays, dow, pad } from './jalali.mjs'
import occasions from './occasions.mjs'

const nth = (y, m, wd, n) => { let c = 0; for (let d = 1; d <= 31; d++) { const t = new Date(Date.UTC(y, m - 1, d)); if (t.getUTCMonth() !== m - 1) break; if (t.getUTCDay() === wd && ++c === n) return [y, m, d] } }
const lastWedBefore = ([y, m, d]) => { let g = [y, m, d]; while (dow(g) !== 3) g = addDays(g, -1); return g }
const occDate = (o, jy) => {
  const gYear = jy + 621
  if (o.j) return j2g(jy, o.j[0], o.j[1])
  if (o.g) return [o.g[0] <= 2 ? gYear + 1 : gYear, o.g[0], o.g[1]]
  switch (o.rule) {
    case 'lastTuesdayEsfand': return addDays(lastWedBefore(addDays(j2g(jy + 1, 1, 1), -1)), -1)
    case 'secondTuesdayFeb': return nth(gYear + 1, 2, 2, 2)
    case 'firstThursdayMay': return nth(gYear, 5, 4, 1)
    case 'programmersDay': { const leap = gYear % 4 === 0 && (gYear % 100 !== 0 || gYear % 400 === 0); return [gYear, 9, leap ? 12 : 13] }
    case 'fourthFridayNov': return addDays(nth(gYear, 11, 4, 4), 1)
  }
}
const rows = occasions.flatMap((o) => [1405, 1406].map((jy) => {
  const g = occDate(o, jy), j = g2j(...g)
  return { id: o.id, date: `${g[0]}-${pad(g[1])}-${pad(g[2])}`, jy: j[0], jm: j[1], jd: j[2], kind: o.kind, title: o.title, note: o.note, cat: o.cat || '', icon: o.spec.icon }
})).sort((a, b) => a.date.localeCompare(b.date))
fs.writeFileSync(new URL('../../serverless-bot/tgcloud/lib/studio_calendar.js', import.meta.url),
  `// GENERATED by growth/calendar/export_studio.mjs from occasions.mjs — do not edit by hand.\nexport const OCCASIONS = ${JSON.stringify(rows, null, 1)}\n`)
