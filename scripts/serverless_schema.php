<?php
// Writes serverless-bot/tgcloud/schema.js from the bot's MySQL database: the same tables and column names,
// so the data moves over as it is and the JavaScript bot reads it like the PHP bot did.
//   php scripts/serverless_schema.php            # writes serverless-bot/tgcloud/schema.js and tgcloud/lib/columns.js
// Types: integer columns → integer, decimals → real, everything else → text. No NOT NULL / defaults (the app sets values).

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}
$root = dirname(__DIR__);
require $root . '/config.php';

// tables of the bot (not other tools sharing the database); finance comes later with the panel
$skip = ['logs_api'];
$tables = array_values(array_diff($pdo->query("SHOW TABLES")->fetchAll(PDO::FETCH_COLUMN), $skip));
sort($tables, SORT_STRING | SORT_FLAG_CASE);

$ident = function (string $s): string {
    $s = preg_replace('/[^A-Za-z0-9_]/', '_', $s);
    return preg_match('/^\d/', $s) ? "_$s" : $s;
};
$out = "// GENERATED by scripts/serverless_schema.php from the PHP bot's MySQL tables — same names, so data imports as is.\n";
$out .= "// Regenerate instead of editing by hand. Columns added later only need `npx tgcloud migrate`.\n";
$out .= "import { table, integer, text, real, index, uniqueIndex } from 'sdk/db'\n\n";
$exports = [];
$columns = [];
foreach ($tables as $t) {
    $cols = $pdo->query("SHOW COLUMNS FROM `$t`")->fetchAll(PDO::FETCH_ASSOC);
    $keys = $pdo->query("SHOW KEYS FROM `$t`")->fetchAll(PDO::FETCH_ASSOC);
    $pk = array_values(array_map(fn($k) => $k['Column_name'], array_filter($keys, fn($k) => $k['Key_name'] === 'PRIMARY')));
    $jsName = $ident($t);
    $exports[] = $jsName;
    $out .= "export const $jsName = table('$t', {\n";
    $used = [];
    foreach ($cols as $c) {
        $type = strtolower($c['Type']);
        $fn = preg_match('/^(tinyint|smallint|mediumint|int|bigint)/', $type) ? 'integer' : (preg_match('/^(decimal|float|double)/', $type) ? 'real' : 'text');
        $key = $ident($c['Field']);
        while (isset($used[$key])) {
            $key .= '_';
        }
        $used[$key] = true;
        $columns[$t][] = $c['Field'];
        $mod = '';
        if (count($pk) === 1 && $pk[0] === $c['Field']) {
            $mod = str_contains($c['Extra'], 'auto_increment') && $fn === 'integer' ? '.primaryKey({ autoIncrement: true })' : '.primaryKey()';
        }
        $out .= "  $key: $fn(" . var_export($c['Field'], true) . ")$mod,\n";
    }
    $idx = [];
    foreach ($keys as $k) {
        if ($k['Key_name'] === 'PRIMARY' && count($pk) === 1) {
            continue;
        }
        $idx[$k['Key_name']]['unique'] = $k['Key_name'] === 'PRIMARY' || !(int) $k['Non_unique'];
        $idx[$k['Key_name']]['cols'][(int) $k['Seq_in_index']] = $ident($k['Column_name']);
    }
    if ($idx) {
        $out .= "}, (t) => ({\n";
        foreach ($idx as $name => $i) {
            ksort($i['cols']);
            $iname = $ident(strtolower($t) . '_' . ($name === 'PRIMARY' ? 'pk' : $name));
            $out .= "  $iname: " . ($i['unique'] ? 'uniqueIndex' : 'index') . "('$iname').on(" . implode(', ', array_map(fn($c) => "t.$c", $i['cols'])) . "),\n";
        }
        $out .= "}))\n\n";
    } else {
        $out .= "})\n\n";
    }
}
// tables only the Serverless bot has
$out .= <<<'JS'
// ---- Serverless-only tables
// the bot's texts (lang/fa.php + edits), key = dotted path like users.status.active
export const texts = table('texts', {
  key: text('key').primaryKey(),
  value: text('value'),
})

// small state: panel tokens, last runs of timed jobs, …
export const kv = table('kv', {
  key: text('key').primaryKey(),
  value: text('value'),
  updated_at: integer('updated_at'),
})

JS;
$columns['texts'] = ['key', 'value'];
$columns['kv'] = ['key', 'value', 'updated_at'];
$dir = $root . '/serverless-bot/tgcloud';
file_put_contents("$dir/schema.js", $out);
file_put_contents("$dir/lib/columns.js", "// GENERATED by scripts/serverless_schema.php: table → columns (the only identifiers dynamic SQL may use)\nexport default " .
    json_encode($columns, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT) . "\n");
echo count($exports) . " tables → $dir/schema.js, lib/columns.js\n";
