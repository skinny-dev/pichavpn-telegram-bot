export default async function ({ compare }) {
  const mask = (x) => JSON.parse(JSON.stringify(x).replace(/"(time|created_at)":"?[^",}]*"?/g, '"$1":"x"').replace(/"(sub_page)":"[^"]*"/g, '"$1":"x"'))
  for (const id of ['mg1', 'mg2', 'mg3', 'mg5']) await compare('mg_order ' + id, 'mg_order', { id }, undefined, { pick: mask })
  await compare('mg_order missing', 'mg_order', { id: 'zz' })
  const act = (name, body, o) => compare(name, 'mg_order_action', {}, body, o)
  await act('renew product', { id: 'mg1', action: 'renew', product_id: 1, notify: true })
  await act('renew custom', { id: 'mg1', action: 'renew', gb: 20, days: 15, charge: true, price: 30000 })
  await act('renew custom nocash', { id: 'mg1', action: 'renew', gb: 20, days: 15, charge: true, price: 99999999 })
  await act('renew bad', { id: 'mg1', action: 'renew', gb: 0, days: 0 })
  await act('renew badprod', { id: 'mg1', action: 'renew', product_id: 999 })
  await act('add_volume', { id: 'mg1', action: 'add_volume', gb: '5.5', notify: true })
  await act('add_volume bad', { id: 'mg1', action: 'add_volume', gb: 0 })
  await act('add_time', { id: 'mg1', action: 'add_time', days: 7 })
  await act('add_time bad', { id: 'mg1', action: 'add_time', days: 5000 })
  await act('toggle', { id: 'mg2', action: 'toggle' })
  await act('reset_usage', { id: 'mg1', action: 'reset_usage' })
  await act('revoke_sub', { id: 'mg1', action: 'revoke_sub' })
  await act('delete (panel keeps user)', { id: 'mg4', action: 'delete', refund: true })
  await act('delete force', { id: 'mg4', action: 'delete', refund: true, force: true })
  await act('edit', { id: 'mg3', action: 'edit', fields: { note: 'یادداشت', price_product: '12,500', Volume: '10.50', Status: 'active', bogus: 'x' } })
  await act('edit bad status', { id: 'mg3', action: 'edit', fields: { Status: 'nope' } })
  await act('edit empty', { id: 'mg3', action: 'edit', fields: { bogus: 1 } })
  await act('message', { id: 'mg1', action: 'message', text: 'سلام <b>x' })
  await act('message nouser', { id: 'mg5', action: 'message', text: 'hi' })
  await act('message empty', { id: 'mg1', action: 'message', text: '' })
  await act('bad action', { id: 'mg1', action: 'zzz' })
  await act('purge', { id: 'mg5', action: 'purge', force: true })
  await compare('mg_order after', 'mg_order', { id: 'mg1' }, undefined, { pick: mask })
  await compare('mg_user', 'mg_user', { id: '7002' })
  await compare('mg_user missing', 'mg_user', { id: '1' })
  const uact = (name, body) => compare(name, 'mg_user_action', {}, body)
  await uact('wallet +', { id: '7003', action: 'wallet', amount: '50,000', reason: 'هدیه', notify: true })
  await uact('wallet -', { id: '7003', action: 'wallet', amount: -1000 })
  await uact('wallet negative', { id: '7003', action: 'wallet', amount: -99999999 })
  await uact('wallet allow negative', { id: '7003', action: 'wallet', amount: -99999999, allow_negative: true })
  await uact('wallet zero', { id: '7003', action: 'wallet', amount: 0 })
  await uact('block', { id: '7004', action: 'block', reason: 'تقلب' })
  await uact('unblock', { id: '7004', action: 'unblock' })
  await uact('user message', { id: '7004', action: 'message', text: 'x' })
  await uact('user edit', { id: '7005', action: 'edit', fields: { namecustom: 'Ali', agent: 'n2', pricediscount: '15', score: '3', number: '0911' } })
  await uact('user edit bad agent', { id: '7005', action: 'edit', fields: { agent: 'zz' } })
  await uact('user bad', { id: '7005', action: 'zz' })
  for (const res of ['users', 'orders', 'payments']) await compare('after ' + res, 'export', { res }, undefined, { pick: (x) => (res === 'payments' ? x.rows.map((r) => ({ ...r, id: 'x', id_order: 'x', time: 'x' })).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))) : x) })
  await compare('service_other', 'mg_order', { id: 'mg1' }, undefined, { pick: (x) => x.history.map((h) => ({ ...h, time: 'x' })).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b))) })
}
